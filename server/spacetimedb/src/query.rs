/// Generic scan for tables that support simple id/workspace_id filtering.
/// Maps alias table names to their real accessors.
fn query_generic_scan(
    ctx: &ReducerContext, query_id: &str, table_name: &str, workspace_id: String,
    filter: &serde_json::Map<String, serde_json::Value>, columns: &[String], now: i64,
) -> Result<(), String> {
    match table_name {
        "context_directory" => {
            for row in ctx.db.context_directory().iter().take(crate::MAX_RESULTS) {
                let val = serde_json::json!({
                    "id": row.id, "workspace_id": row.workspace_id,
                    "name": row.name, "path": row.path,
                    "parent_id": row.parent_id, "description": row.description,
                    "created_at": row.created_at, "updated_at": row.updated_at,
                });
                if filter_matches(&val, filter) && (workspace_id.is_empty() || row.workspace_id == workspace_id) {
                    insert_row(ctx, query_id, table_name, row_to_json(&val, columns), now);
                }
            }
        }
        "delta_pack" => {
            for row in ctx.db.delta_pack().iter().take(crate::MAX_RESULTS) {
                let val = serde_json::json!({
                    "id": row.id, "workspace_id": row.workspace_id,
                    "previous_context_pack_id": row.previous_context_pack_id,
                    "query_hash": row.query_hash,
                    "changed_memory_ids_json": row.changed_memory_ids_json,
                    "removed_memory_ids_json": row.removed_memory_ids_json,
                    "new_memories_json": row.new_memories_json,
                    "estimated_tokens": row.estimated_tokens,
                    "created_at": row.created_at,
                });
                if filter_matches(&val, filter) && (workspace_id.is_empty() || row.workspace_id == workspace_id) {
                    insert_row(ctx, query_id, table_name, row_to_json(&val, columns), now);
                }
            }
        }
        "peer_reputation" => {
            for row in ctx.db.peer_reputation().iter().take(crate::MAX_RESULTS) {
                let val = serde_json::json!({
                    "id": row.id, "helpful_count": row.helpful_count,
                    "unhelpful_count": row.unhelpful_count,
                    "total_feedback": row.total_feedback,
                    "reputation_score": row.reputation_score,
                    "last_feedback_at": row.last_feedback_at,
                });
                if filter_matches(&val, filter) {
                    insert_row(ctx, query_id, table_name, row_to_json(&val, columns), now);
                }
            }
        }
        _ => {}
    }
    Ok(())
}

/// Fallback for tables without a specialized query function.
/// Only supports simple id/workspace_id filtering.
fn query_generic(
    ctx: &ReducerContext, query_id: &str, table_name: &str, _workspace_id: String,
    _filter: &serde_json::Map<String, serde_json::Value>, _columns: &[String], now: i64,
) -> Result<(), String> {
    // For now, just return an empty result set for tables we haven't
    // specialized yet.  The SDK should use table-specific reducers for
    // these tables.
    let _ = (ctx, query_id, table_name, _workspace_id, now);
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_row_to_json_all_columns() {
        let row = serde_json::json!({"id": "abc", "content": "hello", "score": 0.95});
        let result = row_to_json(&row, &[]);
        // All columns — should contain all three keys
        assert!(result.contains("id"));
        assert!(result.contains("content"));
        assert!(result.contains("score"));
    }

    #[test]
    fn test_row_to_json_filtered() {
        let row = serde_json::json!({"id": "abc", "content": "hello", "score": 0.95});
        let result = row_to_json(
            &row,
            &["id".to_string(), "score".to_string()],
        );
        assert!(result.contains("id"));
        assert!(result.contains("score"));
        assert!(!result.contains("content"));
    }

    #[test]
    fn test_filter_matches_string_match() {
        let row = serde_json::json!({"id": "abc", "type": "memory"});
        let mut filter = serde_json::Map::new();
        filter.insert("type".to_string(), serde_json::Value::String("memory".to_string()));
        assert!(filter_matches(&row, &filter));
    }

    #[test]
    fn test_filter_matches_string_mismatch() {
        let row = serde_json::json!({"id": "abc", "type": "memory"});
        let mut filter = serde_json::Map::new();
        filter.insert("type".to_string(), serde_json::Value::String("fact".to_string()));
        assert!(!filter_matches(&row, &filter));
    }

    #[test]
    fn test_filter_matches_missing_key() {
        let row = serde_json::json!({"id": "abc"});
        let mut filter = serde_json::Map::new();
        filter.insert("nonexistent".to_string(), serde_json::Value::String("x".to_string()));
        assert!(!filter_matches(&row, &filter));
    }

    #[test]
    fn test_filter_matches_boolean() {
        let row = serde_json::json!({"active": true});
        let mut filter = serde_json::Map::new();
        filter.insert("active".to_string(), serde_json::Value::Bool(true));
        assert!(filter_matches(&row, &filter));
    }

    #[test]
    fn test_filter_matches_number() {
        let row = serde_json::json!({"score": 0.95});
        let mut filter = serde_json::Map::new();
        filter.insert("score".to_string(), serde_json::json!(0.95));
        assert!(filter_matches(&row, &filter));
    }

    #[test]
    fn test_filter_matches_non_object() {
        let row = serde_json::json!("not an object");
        let filter = serde_json::Map::new();
        assert!(!filter_matches(&row, &filter));
    }
}
