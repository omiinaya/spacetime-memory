fn query_note_backlink(
    ctx: &ReducerContext, query_id: String, workspace_id: String,
    filter: &serde_json::Map<String, serde_json::Value>, columns: &[String], now: i64,
) -> Result<(), String> {
    for nb in ctx.db.note_backlink().iter().take(crate::MAX_RESULTS) {
        // Resolve source note to get workspace context
        let source_note = ctx.db.note().id().find(&nb.source_note_id);
        if let Some(ref sn) = source_note {
            if !workspace_id.is_empty() && sn.workspace_id != workspace_id {
                continue;
            }
        }
        let source_title = source_note.map(|n: crate::note::Note| n.title).unwrap_or_default();
        let target_title = ctx.db.note().id().find(&nb.target_note_id)
            .map(|n: crate::note::Note| n.title)
            .unwrap_or_default();
        let row = serde_json::json!({
            "id": nb.id,
            "source_note_id": nb.source_note_id, "target_note_id": nb.target_note_id,
            "display_text": nb.display_text,
            "source_title": source_title, "target_title": target_title,
            "created_at": nb.created_at,
        });
        if filter_matches(&row, filter) {
            insert_row(ctx, &query_id, "note_backlink", row_to_json(&row, columns), now);
        }
    }
    Ok(())
}

