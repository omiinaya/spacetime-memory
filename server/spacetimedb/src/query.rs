/// Generic result table for read queries against private tables.
///
/// Each query is scoped by `query_id` — the SDK generates a random token,
/// passes it to the reducer, then reads results filtered by that token.
/// This prevents cross-tenant data leakage through result tables.
#[table(accessor = query_result, public)]
#[derive(Debug, Clone)]
pub struct GenericQueryResult {
    #[primary_key]
    pub id: String,
    /// Token generated by the SDK to correlate request with response.
    pub query_id: String,
    /// The table being queried (for SDK disambiguation).
    pub table_name: String,
    /// JSON-serialized row data — all requested columns as a flat object.
    pub row_json: String,
    pub created_at: i64,
}

/// Whitelist of tables that can be queried through the generic endpoint.
/// Only these tables are accessible via `query_table`.
const ALLOWED_TABLES: &[&str] = &[
    "memory", "kg_node", "kg_edge", "kg_community",
    "session", "session_participant", "agent_step",
    "message", "note", "note_backlink", "note_block", "block_reference",
    "profile", "fact",
    "peer",
    "workspace", "space_permission",
    "document", "doc_chunk",
    "tag", "memory_tag",
    "insight", "mental_model",
    "entity_link",
    "search_index",
    "tour", "tour_stop",
    "connector_config",
    "context_pack", "context_directory", "directory_memory_link",
    "context_entry",
    "context_delta_pack", // note: Rust struct is DeltaPack
    "context_delta",      // alias for context_delta_pack (SDK name)
    "directory",          // alias for context_directory (SDK name)
    "peer_reputation",
    "consolidation_log", "merge_suggestion", "backup_entry",
    "memory_feedback", "workspace_config",
    "replication_peer", "replication_log",
    "hierarchy_cluster", "community_hierarchy",
    "proxy_metrics_snapshot",
    "bridge_result", "kg_stats_result", "memory_recommendation",
];

/// Query a private table with auth + workspace enforcement.
///
/// The SDK calls this instead of raw SQL. The caller must be authenticated.
/// For workspace-scoped tables, ``workspace_id`` must be non-empty and the
/// caller must have at least viewer access.
#[reducer]
pub fn query_table(
    ctx: &ReducerContext,
    query_id: String,
    table_name: String,
    workspace_id: String,
    filter_json: String,
    columns_json: String,
) -> Result<(), String> {
    let _account = require_auth(ctx)?;

    // Validate table is whitelisted
    if !ALLOWED_TABLES.contains(&table_name.as_str()) {
        return Err(format!("Table '{}' is not queryable via this endpoint", table_name));
    }

    // If a workspace_id is provided, enforce space access
    if !workspace_id.is_empty() {
        check_space_access(ctx, &workspace_id, &ctx.sender().to_hex(), "viewer")?;
    }

    // Parse filter and columns
    let filter: serde_json::Value = serde_json::from_str(&filter_json)
        .map_err(|e| format!("Invalid filter JSON: {}", e))?;
    let columns: Vec<String> = if columns_json.is_empty() {
        vec![] // empty = all columns
    } else {
        serde_json::from_str(&columns_json)
            .map_err(|e| format!("Invalid columns JSON: {}", e))?
    };

    if !filter.is_object() {
        return Err("filter_json must be a JSON object".to_string());
    }

    let filter_obj = filter.as_object()
        .ok_or_else(|| "filter must be a JSON object".to_string())?;
    let now = now_micros(ctx);

    // ── Route to table-specific query logic ──────────────────────────
    match table_name.as_str() {
        "memory" => query_memory(ctx, query_id, workspace_id, filter_obj, &columns, now),
        "kg_node" => query_kg_node(ctx, query_id, workspace_id, filter_obj, &columns, now),
        "kg_edge" => query_kg_edge(ctx, query_id, workspace_id, filter_obj, &columns, now),
        "kg_community" => query_kg_community(ctx, query_id, filter_obj, &columns, now),
        "session" => query_session(ctx, query_id, workspace_id, filter_obj, &columns, now),
        "message" => query_message(ctx, query_id, filter_obj, &columns, now),
        "note" => query_note(ctx, query_id, workspace_id, filter_obj, &columns, now),
        "note_backlink" => query_note_backlink(ctx, query_id, workspace_id, filter_obj, &columns, now),
        "profile" => query_profile(ctx, query_id, workspace_id, filter_obj, &columns, now),
        "peer" => query_peer(ctx, query_id, workspace_id, filter_obj, &columns, now),
        "workspace" => query_workspace(ctx, query_id, filter_obj, &columns, now),
        "agent_step" => query_agent_step(ctx, query_id, filter_obj, &columns, now),
        "context_pack" => query_context_pack(ctx, query_id, workspace_id, filter_obj, &columns, now),
        "connector_config" => query_connector_config(ctx, query_id, filter_obj, &columns, now),
        // Aliases for SDK table names
        "directory" => query_generic_scan(ctx, &query_id, "context_directory", workspace_id, filter_obj, &columns, now),
        "context_delta" => query_generic_scan(ctx, &query_id, "delta_pack", workspace_id, filter_obj, &columns, now),
        "peer_reputation" => query_generic_scan(ctx, &query_id, "peer_reputation", workspace_id, filter_obj, &columns, now),
        _ => query_generic(ctx, &query_id, &table_name, workspace_id, filter_obj, &columns, now),
    }
}

// ── Per-table query helpers ────────────────────────────────────────────

fn insert_row(ctx: &ReducerContext, query_id: &str, table_name: &str, row_json: String, now: i64) {
    ctx.db.query_result().insert(GenericQueryResult {
        id: uuid_v4(ctx),
        query_id: query_id.to_string(),
        table_name: table_name.to_string(),
        row_json,
        created_at: now,
    });
}

fn row_to_json(row: &serde_json::Value, columns: &[String]) -> String {
    if columns.is_empty() {
        serde_json::to_string(row).unwrap_or_else(|_| "{}".to_string())
    } else if let Some(obj) = row.as_object() {
        let filtered: serde_json::Map<String, serde_json::Value> = obj.iter()
            .filter(|(k, _)| columns.contains(k))
            .map(|(k, v)| (k.clone(), v.clone()))
            .collect();
        serde_json::to_string(&filtered).unwrap_or_else(|_| "{}".to_string())
    } else {
        serde_json::to_string(row).unwrap_or_else(|_| "{}".to_string())
    }
}

fn filter_matches(row: &serde_json::Value, filter: &serde_json::Map<String, serde_json::Value>) -> bool {
    let obj = match row.as_object() {
        Some(o) => o,
        None => return false,
    };
    for (key, expected) in filter {
        let actual = match obj.get(key) {
            Some(v) => v,
            None => return false,
        };
        // String equality for simple filters; JSON match for complex
        if expected.is_string() && actual.is_string() {
            if expected.as_str() != actual.as_str() {
                return false;
            }
        } else if expected.is_boolean() && actual.is_boolean() {
            if expected.as_bool() != actual.as_bool() {
                return false;
            }
        } else if expected.is_number() && actual.is_number() {
            // Compare as f64 for simplicity
            let e = expected.as_f64().unwrap_or(0.0);
            let a = actual.as_f64().unwrap_or(0.0);
            if (e - a).abs() > f64::EPSILON {
                return false;
            }
        // Coerce string to boolean for SDK convenience (list_memories sends "true"/"false")
        } else if expected.is_string() && actual.is_boolean() {
            let expected_bool = expected.as_str().map(|s| s.eq_ignore_ascii_case("true")).unwrap_or(false);
            if expected_bool != actual.as_bool().unwrap_or(false) {
                return false;
            }
        // Coerce string to number for SDK convenience
        } else if expected.is_string() && actual.is_number() {
            let expected_num: f64 = match expected.as_str().and_then(|s| s.parse().ok()) {
                Some(n) => n,
                None => return false,
            };
            let actual_num = actual.as_f64().unwrap_or(0.0);
            if (expected_num - actual_num).abs() > f64::EPSILON {
                return false;
            }
        } else if expected != actual {
            return false;
        }
    }
    true
}

// ── Table-specific query implementations ───────────────────────────────

fn query_memory(
    ctx: &ReducerContext, query_id: String, workspace_id: String,
    filter: &serde_json::Map<String, serde_json::Value>, columns: &[String], now: i64,
) -> Result<(), String> {
    for m in ctx.db.memory().iter().filter(|m: &crate::memory::Memory| {
        (workspace_id.is_empty() || m.workspace_id == workspace_id) && m.is_active
    }).take(crate::MAX_RESULTS) {
        let row = serde_json::json!({
            "id": m.id, "workspace_id": m.workspace_id, "content": m.content,
            "summary": m.summary, "memory_type": m.memory_type,
            "peer_id": m.peer_id, "observer_id": m.observer_id,
            "source_session_id": m.source_session_id, "source_message_id": m.source_message_id,
            "entities_json": m.entities_json, "confidence": m.confidence,
            "tier": m.tier, "is_active": m.is_active,
            "expires_at": m.expires_at,
            "created_at": m.created_at, "updated_at": m.updated_at,
        });
        if filter_matches(&row, filter) {
            insert_row(ctx, &query_id, "memory", row_to_json(&row, columns), now);
        }
    }
    Ok(())
}

